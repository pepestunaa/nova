const std = @import("std");
const Io = std.Io;

const raw_caps = @import("tables/DiscPromoteLimit");
const raw_config = @import("tables/Config");
const raw_exp_items = @import("tables/DiscItemExp");
const raw_promotions = @import("tables/DiscPromote");
const raw_strengthen = @import("tables/DiscStrengthen");

const raw_cap_count: usize = raw_caps.len;
const raw_exp_item_count: usize = raw_exp_items.len;
const raw_promotion_count: usize = raw_promotions.len;
const raw_strengthen_count: usize = raw_strengthen.len;

//

const max_costs = 3;
const strengthen_rows = normalizeStrengthen();
const exp_items = normalizeExpItems();
const promotion_rows = normalizePromotions();
const phase_caps = normalizeCaps();
const max_level = maximumLevel(strengthen_rows);
const max_phase = maximumPhase(phase_caps);
const strengthen_group_count = countGroups(strengthen_rows, strengthenGroup);
const promotion_group_count = countGroups(promotion_rows, promotionGroup);
const strengthen_gold_per_1000_exp = singleConfigValue("DiscStrengthenGoldFactor");
const max_star = maximum(configUnsignedList("DiscRarityLimitBreakMax"));

const StrengthenRow = struct {
    id: u32,
    exp: u32,
};

const ExpItem = struct {
    item_id: u32,
    exp: u32,
};

const PromoteRow = struct {
    id: u32,
    item_ids: [max_costs]u32,
    quantities: [max_costs]i32,
    gold: i32,
};

const PhaseCap = struct {
    rarity: u8,
    phase: u8,
    level: u8,
    player_level: u8,
};

const Cost = struct {
    material: u8,
    quantity: i32,
};

const Costs = struct {
    entries: [max_costs]Cost = @splat(.{ .material = 0, .quantity = 0 }),
    count: u8 = 0,
};

const PromoteStep = struct {
    gold: i32,
    costs: Costs,
};

const PromoteShape = [max_phase]PromoteStep;

const PromoteGroup = struct {
    group: u32,
    shape: u8,
    materials: u8,
};

const PromotionData = struct {
    shapes: [promotion_group_count]PromoteShape = undefined,
    shape_count: usize = 0,
    material_sets: [promotion_group_count][max_costs]u32 = undefined,
    material_set_count: usize = 0,
    groups: [promotion_group_count]PromoteGroup = undefined,
    group_count: usize = 0,
};

pub fn generate(_: std.process.Init, writer: *Io.Writer) anyerror!void {
    try writer.writeAll(
        \\//! Generated by `zig build generate-assets -- disc_progression`.
        \\//! Do not edit manually.
        \\
        \\pub const max_costs =
    );
    try writer.print("{d};\n", .{max_costs});
    try writer.print(
        "pub const max_level = {d};\npub const max_phase = {d};\npub const max_exp = {d};\npub const max_star = {d};\n\n",
        .{ max_level, max_phase, maximumExp(strengthen_rows), max_star },
    );
    try writer.writeAll(
        \\pub const Cost = struct { material: u8, quantity: i32 };
        \\pub const Costs = struct { entries: [max_costs]Cost, count: u8 };
        \\pub const PromoteStep = struct { gold: i32, costs: Costs };
        \\pub const StrengthenCurve = struct { group: u32, costs: [max_level - 1]u32 };
        \\pub const ExpItem = struct { item_id: u32, exp: u32 };
        \\pub const PhaseCap = struct { rarity: u8, phase: u8, level: u8, player_level: u8 };
        \\pub const PromoteGroup = struct { group: u32, shape: u8, materials: u8 };
        \\
        \\
    );

    try writeExpItems(writer);
    try writeStrengthenGoldFactors(writer);
    try writeStrengthenCurves(writer);
    try writePhaseCaps(writer);
    try writePromotions(writer, try buildPromotions());
}

fn writeStrengthenGoldFactors(writer: *Io.Writer) !void {
    try writer.print(
        "pub const strengthen_gold_per_1000_exp = {d};\n\n",
        .{strengthen_gold_per_1000_exp},
    );
}

fn writeExpItems(writer: *Io.Writer) !void {
    try writer.writeAll("pub const exp_items = [_]ExpItem{\n");
    for (exp_items) |item|
        try writer.print("    .{{ .item_id = {d}, .exp = {d} }},\n", .{ item.item_id, item.exp });
    try writer.writeAll("};\n\n");
}

fn writeStrengthenCurves(writer: *Io.Writer) !void {
    try writer.writeAll("pub const strengthen_curves = [_]StrengthenCurve{\n");
    var start: usize = 0;
    while (start < strengthen_rows.len) {
        const group = strengthenGroup(strengthen_rows[start]);
        try writer.print("    .{{ .group = {d}, .costs = .{{\n", .{group});
        var level: u32 = 1;
        while (start < strengthen_rows.len and strengthenGroup(strengthen_rows[start]) == group) : (start += 1) {
            const entry = strengthen_rows[start];
            if (entry.id != group * 1000 + level)
                return error.InvalidStrengthenOrdering;
            if (level != 1)
                try writer.print("        {d}{s}\n", .{
                    entry.exp,
                    if (level < max_level) "," else "",
                });
            level += 1;
        }
        if (level != max_level + 1)
            return error.InvalidStrengthenLength;
        try writer.writeAll("    }, },\n");
    }
    try writer.writeAll("};\n\n");
}

fn writePhaseCaps(writer: *Io.Writer) !void {
    try writer.writeAll("pub const phase_caps = [_]PhaseCap{\n");
    for (phase_caps) |cap| try writer.print(
        "    .{{ .rarity = {d}, .phase = {d}, .level = {d}, .player_level = {d} }},\n",
        .{
            cap.rarity,
            cap.phase,
            cap.level,
            cap.player_level,
        },
    );
    try writer.writeAll("};\n\n");
}

fn writePromotions(writer: *Io.Writer, promotions: PromotionData) !void {
    try writer.writeAll("pub const promote_shapes = [_][max_phase]PromoteStep{\n");
    for (promotions.shapes[0..promotions.shape_count]) |shape| {
        try writer.writeAll("    .{\n");
        for (shape) |step| {
            try writer.print("        .{{ .gold = {d}, .costs = .{{ .entries = .{{", .{step.gold});
            for (step.costs.entries) |cost|
                try writer.print(" .{{ .material = {d}, .quantity = {d} }},", .{ cost.material, cost.quantity });
            try writer.print(" }}, .count = {d}, }}, }},\n", .{step.costs.count});
        }
        try writer.writeAll("    },\n");
    }
    try writer.writeAll("};\n\n");

    try writer.writeAll("pub const promote_material_sets = [_][max_costs]u32{\n");
    for (promotions.material_sets[0..promotions.material_set_count]) |materials|
        try writer.print("    .{{ {d}, {d}, {d} }},\n", .{ materials[0], materials[1], materials[2] });
    try writer.writeAll("};\n\n");

    try writer.writeAll("pub const promote_groups = [_]PromoteGroup{\n");
    for (promotions.groups[0..promotions.group_count]) |group|
        try writer.print(
            "    .{{ .group = {d}, .shape = {d}, .materials = {d} }},\n",
            .{ group.group, group.shape, group.materials },
        );
    try writer.writeAll("};\n");
}

fn buildPromotions() !PromotionData {
    var result: PromotionData = .{};
    var start: usize = 0;
    while (start < promotion_rows.len) {
        const group = promotionGroup(promotion_rows[start]);
        var materials: [max_costs]u32 = @splat(0);
        var material_count: usize = 0;
        var shape: PromoteShape = undefined;
        var phase: u32 = 1;
        while (start < promotion_rows.len and promotionGroup(promotion_rows[start]) == group) : (start += 1) {
            const entry = promotion_rows[start];
            if (entry.id != group * 1000 + phase)
                return error.InvalidPromotionOrdering;
            shape[phase - 1] = .{
                .gold = entry.gold,
                .costs = normalizedCosts(entry, &materials, &material_count),
            };
            phase += 1;
        }
        if (phase != max_phase + 1)
            return error.InvalidPromotionLength;

        const shape_index = appendUniqueShape(&result, shape);
        const material_index = appendUniqueMaterials(&result, materials);
        result.groups[result.group_count] = .{
            .group = group,
            .shape = @intCast(shape_index),
            .materials = @intCast(material_index),
        };
        result.group_count += 1;
    }
    return result;
}

fn normalizedCosts(entry: anytype, materials: *[max_costs]u32, material_count: *usize) Costs {
    var result: Costs = .{};
    for (entry.item_ids, entry.quantities) |item_id, quantity| {
        if (item_id == 0 or quantity == 0)
            continue;

        var material: usize = 0;
        while (material < material_count.* and materials[material] != item_id) : (material += 1) {}
        if (material == material_count.*) {
            if (material == materials.len) unreachable;
            materials[material] = item_id;
            material_count.* += 1;
        }
        result.entries[result.count] = .{ .material = @intCast(material), .quantity = quantity };
        result.count += 1;
    }
    return result;
}

fn appendUniqueShape(result: *PromotionData, shape: PromoteShape) usize {
    for (result.shapes[0..result.shape_count], 0..) |existing, index|
        if (std.meta.eql(existing, shape)) return index;
    result.shapes[result.shape_count] = shape;
    result.shape_count += 1;
    return result.shape_count - 1;
}

fn appendUniqueMaterials(result: *PromotionData, materials: [max_costs]u32) usize {
    for (result.material_sets[0..result.material_set_count], 0..) |existing, index|
        if (std.meta.eql(existing, materials)) return index;
    result.material_sets[result.material_set_count] = materials;
    result.material_set_count += 1;
    return result.material_set_count - 1;
}

fn strengthenGroup(entry: anytype) u32 {
    return entry.id / 1000;
}

fn promotionGroup(entry: anytype) u32 {
    return entry.id / 1000;
}

fn countGroups(comptime entries: anytype, comptime group: anytype) usize {
    var count: usize = 0;
    var previous: u32 = 0;
    inline for (entries) |entry| {
        const value = group(entry);
        if (count == 0 or value != previous) {
            count += 1;
            previous = value;
        }
    }
    return count;
}

fn maximumLevel(comptime entries: anytype) u32 {
    var result: u32 = 0;
    inline for (entries) |entry| result = @max(result, entry.id % 1000);
    return result;
}

fn maximumExp(comptime entries: anytype) u32 {
    var result: u32 = 0;
    inline for (entries) |entry| {
        result = @max(result, entry.exp);
    }
    return result;
}

fn maximumPhase(comptime entries: anytype) u32 {
    var result: u32 = 0;
    inline for (entries) |entry| result = @max(result, entry.phase);
    return result;
}

fn maximum(values: []const u32) u32 {
    var result: u32 = 0;
    for (values) |value| result = @max(result, value);
    return result;
}

fn configUnsignedList(comptime id: []const u8) []const u32 {
    inline for (raw_config) |entry| {
        if (!std.mem.eql(u8, entry.id, id))
            continue;

        var result: []const u32 = &.{};
        var values = std.mem.splitScalar(u8, entry.value, ',');
        while (values.next()) |value|
            result = result ++ [1]u32{std.fmt.parseInt(u32, value, 10) catch
                @compileError("invalid unsigned integer in Config entry '" ++ id ++ "'")};
        if (result.len == 0)
            @compileError("empty Config integer list '" ++ id ++ "'");
        return result;
    }
    @compileError("missing Config entry '" ++ id ++ "'");
}

fn singleConfigValue(comptime id: []const u8) u32 {
    const values = configUnsignedList(id);
    for (values[1..]) |value| {
        if (value != values[0])
            @compileError("Config entry '" ++ id ++ "' must use one value for every rarity");
    }
    return values[0];
}

fn normalizeStrengthen() [raw_strengthen_count]StrengthenRow {
    var result: [raw_strengthen_count]StrengthenRow = undefined;
    inline for (raw_strengthen, 0..) |entry, index| result[index] = .{
        .id = entry.id,
        .exp = fieldOrZero(entry, "exp"),
    };
    return result;
}

fn normalizeExpItems() [raw_exp_item_count]ExpItem {
    var result: [raw_exp_item_count]ExpItem = undefined;
    inline for (raw_exp_items, 0..) |entry, index| result[index] = .{
        .item_id = entry.item_id,
        .exp = entry.exp,
    };
    return result;
}

fn normalizePromotions() [raw_promotion_count]PromoteRow {
    @setEvalBranchQuota(100_000);

    var result: [raw_promotion_count]PromoteRow = undefined;
    inline for (raw_promotions, 0..) |entry, row| {
        var item_ids: [max_costs]u32 = undefined;
        var quantities: [max_costs]i32 = undefined;
        inline for (1..max_costs + 1) |index| {
            item_ids[index - 1] = fieldOrZero(entry, std.fmt.comptimePrint("item_id{d}", .{index}));
            quantities[index - 1] = @intCast(fieldOrZero(entry, std.fmt.comptimePrint("num{d}", .{index})));
        }
        result[row] = .{
            .id = entry.id,
            .item_ids = item_ids,
            .quantities = quantities,
            .gold = @intCast(fieldOrZero(entry, "expense_gold")),
        };
    }
    return result;
}

fn normalizeCaps() [raw_cap_count]PhaseCap {
    @setEvalBranchQuota(10_000);

    var result: [raw_cap_count]PhaseCap = undefined;
    inline for (raw_caps, 0..) |entry, index| result[index] = .{
        .rarity = entry.rarity,
        .phase = std.fmt.parseInt(u8, entry.phase, 10) catch unreachable,
        .level = std.fmt.parseInt(u8, entry.max_level, 10) catch unreachable,
        .player_level = entry.world_class_limit,
    };
    return result;
}

fn fieldOrZero(value: anytype, comptime name: []const u8) u32 {
    if (@hasField(@TypeOf(value), name))
        return @intCast(@field(value, name));
    return 0;
}
