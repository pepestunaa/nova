const std = @import("std");
const Io = std.Io;

const raw_growth_nodes = @import("tables/StarTowerGrowthNode");
const raw_growth_text = @import("tables/lang/StarTowerGrowthNode");
const raw_quest_text = @import("tables/lang/StarTowerQuest");
const raw_quests = @import("tables/StarTowerQuest");

//

const max_required_nodes = 2;

const Condition = enum {
    activate_nodes,
    enter_ascension,
    clear_difficulty,
    shop_purchase,
    musical_note,
    record_rating,
    enhancement_machine,
    harmony_skill,
    monolith_log,
    discounted_shop_purchase,
    surprise_note,
    butterflies_inside,
    potential_boost,
    refresh_potentials,
    restock_shop,
};

const Target = struct {
    condition: Condition,
    parameter: u32,
    target: u32,
};

const NodeList = struct {
    ids: [max_required_nodes]u32 = @splat(0),
    count: u8 = 0,
};

pub fn generate(_: std.process.Init, writer: *Io.Writer) anyerror!void {
    @setEvalBranchQuota(1_000_000);

    try writer.writeAll(
        \\//! Generated by `zig build generate-assets -- research_project`.
        \\//! Do not edit manually.
        \\//! Normal quest targets are parsed from the English StarTowerQuest titles.
        \\
        \\pub const Condition = enum(u8) {
        \\
    );
    for (std.enums.values(Condition)) |condition|
        try writer.print("    {s},\n", .{@tagName(condition)});
    try writer.writeAll(
        \\};
        \\
        \\pub const max_required_nodes = 2;
        \\
        \\pub const Quest = struct {
        \\    id: u32,
        \\    condition: Condition,
        \\    parameter: u32,
        \\    target: u32,
        \\    required_nodes: [max_required_nodes]u32,
        \\    required_node_count: u8,
        \\};
        \\
    );
    try writer.writeByte('\n');
    try writer.writeAll("pub const quests = [_]Quest{\n");
    inline for (raw_quests) |quest| {
        const nodes: NodeList = comptime if (quest.tower_quest_type == 1)
            coreNodes(quest.id)
        else
            .{};
        const target: Target = comptime switch (quest.tower_quest_type) {
            1 => .{
                .condition = .activate_nodes,
                .parameter = 0,
                .target = nodes.count,
            },
            2 => normalTarget(quest.id, questTitle(quest.id)),
            else => @compileError("unsupported StarTowerQuest type"),
        };
        try writer.print(
            "    .{{ .id = {d}, .condition = .{s}, .parameter = {d}, .target = {d}, .required_nodes = .{{ {d}, {d} }}, .required_node_count = {d} }},\n",
            .{
                quest.id,
                @tagName(target.condition),
                target.parameter,
                target.target,
                nodes.ids[0],
                nodes.ids[1],
                nodes.count,
            },
        );
    }
    try writer.writeAll("};\n");
}

fn normalTarget(comptime quest_id: u32, comptime raw_title: []const u8) Target {
    const title = if (std.mem.endsWith(u8, raw_title, "."))
        raw_title[0 .. raw_title.len - 1]
    else
        raw_title;

    if (timesAfter(title, "Participate in Ascension ")) |count|
        return .{ .condition = .enter_ascension, .parameter = 0, .target = count };
    if (clearDifficulty(title)) |target|
        return target;
    if (timesAfterEither(
        title,
        "Purchase from the Shop a total of ",
        "Purchase from the Shop ",
    )) |count|
        return .{ .condition = .shop_purchase, .parameter = 0, .target = count };
    if (numberBetween(title, "Collect a total of ", " Musical Notes")) |count|
        return .{ .condition = .musical_note, .parameter = 0, .target = count };
    if (recordTarget(title)) |target|
        return target;
    if (timesAfterEither(
        title,
        "Use the Enhancement Machine a total of ",
        "Use the Enhancement Machine ",
    )) |count|
        return .{ .condition = .enhancement_machine, .parameter = 0, .target = count };
    if (timesAfter(title, "Activate Harmony Skill ")) |count|
        return .{ .condition = .harmony_skill, .parameter = 0, .target = count };
    if (numberBetween(title, "Collect a total of ", " Anecdotes in Monolith Log")) |count|
        return .{ .condition = .monolith_log, .parameter = 0, .target = count };
    if (timesAfter(title, "Purchase discounted items ")) |count|
        return .{ .condition = .discounted_shop_purchase, .parameter = 0, .target = count };
    if (timesAfter(title, "Trigger Note of Surprise ")) |count|
        return .{ .condition = .surprise_note, .parameter = 0, .target = count };
    if (numberBetween(
        title,
        "Trigger Butterflies Inside ",
        " times when acquiring new Potentials",
    )) |count|
        return .{ .condition = .butterflies_inside, .parameter = 0, .target = count };
    if (numberBetween(
        title,
        "Trigger Potential Boost ",
        " times when enhancing Potentials",
    )) |count|
        return .{ .condition = .potential_boost, .parameter = 0, .target = count };
    if (timesAfter(title, "Refresh Potentials ")) |count|
        return .{ .condition = .refresh_potentials, .parameter = 0, .target = count };
    if (timesAfter(title, "Restock Shop ")) |count|
        return .{ .condition = .restock_shop, .parameter = 0, .target = count };

    @compileError(std.fmt.comptimePrint(
        "unsupported normal StarTowerQuest title for ID {d}: '{s}'",
        .{ quest_id, raw_title },
    ));
}

fn clearDifficulty(comptime title: []const u8) ?Target {
    if (!std.mem.startsWith(u8, title, "Clear ")) return null;

    const difficulty_marker = "Difficulty ";
    const difficulty_start = (std.mem.indexOf(u8, title, difficulty_marker) orelse
        return null) + difficulty_marker.len;
    const separator = " or above ";
    const separator_start = std.mem.indexOfPos(u8, title, difficulty_start, separator) orelse
        return null;
    const count_text = title[separator_start + separator.len ..];
    const count = if (std.mem.eql(u8, count_text, "once"))
        1
    else
        parseTimes(count_text) orelse return null;

    return .{
        .condition = .clear_difficulty,
        .parameter = parseNumber(title[difficulty_start..separator_start]),
        .target = count,
    };
}

fn recordTarget(comptime title: []const u8) ?Target {
    const prefix = "Acquire ";
    if (!std.mem.startsWith(u8, title, prefix)) return null;

    const normal_marker = " Record with a rating level of ";
    const new_marker = " new Record with a rating level of ";
    const marker, const marker_start = if (std.mem.indexOf(u8, title, new_marker)) |start|
        .{ new_marker, start }
    else if (std.mem.indexOf(u8, title, normal_marker)) |start|
        .{ normal_marker, start }
    else
        return null;

    return .{
        .condition = .record_rating,
        .parameter = parseNumber(title[marker_start + marker.len ..]),
        .target = parseNumber(title[prefix.len..marker_start]),
    };
}

fn timesAfter(comptime text: []const u8, comptime prefix: []const u8) ?u32 {
    if (!std.mem.startsWith(u8, text, prefix)) return null;
    return parseTimes(text[prefix.len..]);
}

fn timesAfterEither(
    comptime text: []const u8,
    comptime first_prefix: []const u8,
    comptime second_prefix: []const u8,
) ?u32 {
    if (timesAfter(text, first_prefix)) |count| return count;
    return timesAfter(text, second_prefix);
}

fn parseTimes(comptime text: []const u8) ?u32 {
    const singular = " time";
    const plural = " times";
    const number = if (std.mem.endsWith(u8, text, plural))
        text[0 .. text.len - plural.len]
    else if (std.mem.endsWith(u8, text, singular))
        text[0 .. text.len - singular.len]
    else
        return null;

    return parseNumber(number);
}

fn numberBetween(
    comptime text: []const u8,
    comptime prefix: []const u8,
    comptime suffix: []const u8,
) ?u32 {
    if (!std.mem.startsWith(u8, text, prefix) or
        !std.mem.endsWith(u8, text, suffix) or
        text.len <= prefix.len + suffix.len)
        return null;

    return parseNumber(text[prefix.len .. text.len - suffix.len]);
}

fn parseNumber(comptime text: []const u8) u32 {
    var result: u32 = 0;
    var digit_count: usize = 0;
    for (text) |byte| switch (byte) {
        '0'...'9' => {
            result = result * 10 + byte - '0';
            digit_count += 1;
        },
        ',' => {},
        else => @compileError(std.fmt.comptimePrint(
            "invalid number '{s}' in StarTowerQuest title",
            .{text},
        )),
    };
    if (digit_count == 0)
        @compileError("empty number in StarTowerQuest title");

    return result;
}

fn coreNodes(comptime quest_id: u32) NodeList {
    const title = questTitle(quest_id);
    const prefixed = if (std.mem.startsWith(u8, title, "Activate Node: "))
        title["Activate Node: ".len..]
    else if (std.mem.startsWith(u8, title, "Activate Nodes: "))
        title["Activate Nodes: ".len..]
    else if (std.mem.startsWith(u8, title, "Activate Node "))
        title["Activate Node ".len..]
    else if (std.mem.startsWith(u8, title, "Activate Nodes "))
        title["Activate Nodes ".len..]
    else
        @compileError("unexpected Research Project core title");
    const unlock_suffix = " (Complete to unlock more research)";
    const names = if (std.mem.endsWith(u8, prefixed, unlock_suffix))
        prefixed[0 .. prefixed.len - unlock_suffix.len]
    else
        prefixed;

    var result: NodeList = .{};
    var words = std.mem.splitSequence(u8, names, " and ");
    while (words.next()) |name| {
        var matched_id: ?u32 = null;
        inline for (raw_growth_nodes) |node| {
            if (!std.mem.eql(u8, name, growthNodeTitle(node.id))) continue;
            if (matched_id != null)
                @compileError("ambiguous Monolith Research node name");
            matched_id = node.id;
        }
        if (matched_id == null)
            @compileError("Research Project title does not match a Monolith Research node");
        if (result.count == result.ids.len)
            @compileError("Research Project requires too many nodes");
        result.ids[result.count] = matched_id.?;
        result.count += 1;
    }

    if (result.count == 0)
        @compileError("Research Project has no growth-node target");

    return result;
}

fn questTitle(comptime id: u32) []const u8 {
    return @field(raw_quest_text, std.fmt.comptimePrint("star_tower_quest_{d}_1", .{id}));
}

fn growthNodeTitle(comptime id: u32) []const u8 {
    return @field(raw_growth_text, std.fmt.comptimePrint("star_tower_growth_node_{d}_1", .{id}));
}
