const std = @import("std");
const Io = std.Io;

const raw_advances = @import("tables/CharacterAdvance");
const raw_characters = @import("tables/Character");
const raw_exp_items = @import("tables/CharItemExp");
const raw_grades = @import("tables/CharGrade");
const raw_level_caps = @import("tables/CharRaritySequence");
const raw_skill_upgrades = @import("tables/CharacterSkillUpgrade");
const raw_talent_groups = @import("tables/TalentGroup");
const raw_talents = @import("tables/Talent");
const raw_upgrades = @import("tables/CharacterUpgrade");

const raw_exp_item_count: usize = raw_exp_items.len;
const raw_level_cap_count: usize = raw_level_caps.len;
const raw_upgrade_count: usize = raw_upgrades.len;

//

const max_costs = @max(
    maximumCostSlots(raw_advances),
    maximumCostSlots(raw_skill_upgrades),
);
const level_cost_count = maximumRowsByKey(raw_upgrades, levelCostGroup);
const level_cap_count = maximumRowsByField(raw_level_caps, "grade");
const advance_level_count = maximumRowsByField(raw_advances, "group");
const skill_level_count = maximumRowsByField(raw_skill_upgrades, "group");
const advance_group_count = countGroups(raw_advances, "group");
const skill_group_count = countGroups(raw_skill_upgrades, "group");
const advance_material_count = maximumMaterials(raw_advances);
const skill_material_count = maximumMaterials(raw_skill_upgrades);

const RawCost = struct {
    item_id: u32,
    quantity: i32,
};

const RawCosts = struct {
    entries: [max_costs]RawCost = @splat(.{ .item_id = 0, .quantity = 0 }),
    count: u8 = 0,
};

const Cost = struct {
    material: u8,
    quantity: i32,
};

const Costs = struct {
    entries: [max_costs]Cost = @splat(.{ .material = 0, .quantity = 0 }),
    count: u8 = 0,
};

const LevelCost = struct {
    level: u8,
    exp: u32,
};

const LevelCap = struct {
    advance: u8,
    level: u8,
    player_level: u8,
};

const AdvanceStep = struct {
    gold: i32,
    costs: Costs,
};

const SkillStep = struct {
    required_advance: u8,
    gold: i32,
    costs: Costs,
};

const AdvanceEntry = struct { gold: i32, costs: RawCosts };
const SkillEntry = struct { required_advance: u8, gold: i32, costs: RawCosts };

const MaterialMapping = struct {
    group: u32,
    material_set: u8,
};

const LevelCostData = struct {
    rows: [level_cost_count]LevelCost,
    max_exp: u32,
};

const LevelCapData = struct {
    rows: [level_cap_count]LevelCap,
};

const AdvanceData = struct {
    shape: [advance_level_count]AdvanceStep,
    materials: [advance_group_count][advance_material_count]u32,
    material_set_count: usize,
    groups: [advance_group_count]MaterialMapping,
    group_count: usize,
};

const SkillData = struct {
    shape: [skill_level_count]SkillStep,
    materials: [skill_group_count][skill_material_count]u32,
    material_set_count: usize,
    groups: [skill_group_count]MaterialMapping,
    group_count: usize,
    max_required_advance: u8,
};

const TalentLayout = struct {
    groups_per_character: u8,
    max_index: u8,
    max_entries_per_group: u8,
};

pub fn generate(_: std.process.Init, writer: *Io.Writer) anyerror!void {
    @setEvalBranchQuota(1_000_000);

    const level_costs = try buildLevelCosts();
    const level_caps = try buildLevelCaps();
    const advances = try buildAdvances();
    const skills = try buildSkills();
    const talent_layout = try validateTalentLayout();
    try validateCharacters();

    try writer.writeAll(
        \\//! Generated by `zig build generate-assets -- character_progression`.
        \\//! Do not edit manually.
        \\
        \\pub const max_costs =
    );
    try writer.print("{d};\n", .{max_costs});
    try writer.print(
        "pub const exp_item_count = {d};\npub const max_level = {d};\npub const max_exp = {d};\npub const max_advance = {d};\npub const max_skill_level = {d};\npub const max_skill_upgrade_rank = {d};\npub const talent_group_count = {d};\npub const max_talent_index = {d};\npub const max_talents_per_group = {d};\n\n",
        .{
            raw_exp_item_count,
            level_costs.rows[level_costs.rows.len - 1].level,
            level_costs.max_exp,
            level_caps.rows.len - 1,
            skill_level_count,
            skills.max_required_advance,
            talent_layout.groups_per_character,
            talent_layout.max_index,
            talent_layout.max_entries_per_group,
        },
    );
    try writer.writeAll(
        \\pub const Character = struct { id: u32, grade: u8, advance_materials: u8, skill_materials: u8 };
        \\pub const Cost = struct { material: u8, quantity: i32 };
        \\pub const Costs = struct { entries: [max_costs]Cost, count: u8 };
        \\pub const LevelCost = struct { level: u8, exp: u32 };
        \\pub const LevelCap = struct { advance: u8, level: u8, player_level: u8 };
        \\pub const ExpItem = struct { item_id: u32, exp: u32 };
        \\pub const AdvanceStep = struct { gold: i32, costs: Costs };
        \\pub const SkillStep = struct { required_advance: u8, gold: i32, costs: Costs };
        \\pub const Grade = struct { id: u8, fragments_per_node: i32 };
        \\
        \\
    );

    writeCharacters(writer, advances, skills);
    writeLevelCosts(writer, level_costs.rows);
    writeLevelCaps(writer, level_caps.rows);
    writeExpItems(writer);
    writeAdvanceCurves(writer, advances);
    writeSkillCurves(writer, skills);
    writeGrades(writer);
}

fn writeCharacters(writer: *Io.Writer, advances: AdvanceData, skills: SkillData) void {
    writer.writeAll("pub const characters = [_]Character{\n") catch unreachable;
    inline for (raw_characters) |raw| writer.print(
        "    .{{ .id = {d}, .grade = {d}, .advance_materials = {d}, .skill_materials = {d} }},\n",
        .{
            raw.id,
            raw.grade,
            materialSet(advances.groups[0..advances.group_count], raw.id),
            materialSet(skills.groups[0..skills.group_count], raw.id),
        },
    ) catch unreachable;
    writer.writeAll("};\n\n") catch unreachable;
}

fn writeLevelCosts(writer: *Io.Writer, rows: [level_cost_count]LevelCost) void {
    writer.writeAll("pub const level_costs = [_]LevelCost{\n") catch unreachable;
    for (rows) |row| writer.print(
        "    .{{ .level = {d}, .exp = {d} }},\n",
        .{ row.level, row.exp },
    ) catch unreachable;
    writer.writeAll("};\n\n") catch unreachable;
}

fn writeLevelCaps(writer: *Io.Writer, rows: [level_cap_count]LevelCap) void {
    writer.writeAll("pub const level_caps = [_]LevelCap{\n") catch unreachable;
    for (rows) |row| writer.print(
        "    .{{ .advance = {d}, .level = {d}, .player_level = {d} }},\n",
        .{ row.advance, row.level, row.player_level },
    ) catch unreachable;
    writer.writeAll("};\n\n") catch unreachable;
}

fn writeExpItems(writer: *Io.Writer) void {
    writer.writeAll("pub const exp_items = [_]ExpItem{\n") catch unreachable;
    inline for (raw_exp_items) |raw| writer.print(
        "    .{{ .item_id = {d}, .exp = {d} }},\n",
        .{ raw.item_id, raw.exp_value },
    ) catch unreachable;
    writer.writeAll("};\n\n") catch unreachable;
}

fn writeAdvanceCurves(writer: *Io.Writer, data: AdvanceData) void {
    writer.print("pub const advance_shape = [_]AdvanceStep{{\n", .{}) catch unreachable;
    for (data.shape) |row| {
        writer.print("    .{{ .gold = {d}, .costs = ", .{row.gold}) catch unreachable;
        writeCosts(writer, row.costs);
        writer.writeAll(" },\n") catch unreachable;
    }
    writer.writeAll("};\n\npub const advance_materials = [_][" ++
        std.fmt.comptimePrint("{d}", .{advance_material_count}) ++
        "]u32{\n") catch unreachable;
    for (data.materials[0..data.material_set_count]) |material_set| {
        writer.writeAll("    .{ ") catch unreachable;
        for (material_set, 0..) |item_id, i| writer.print(
            "{d}{s} ",
            .{ item_id, if (i != advance_material_count - 1) "," else "" },
        ) catch unreachable;
        writer.writeAll("},\n") catch unreachable;
    }
    writer.writeAll("};\n\n") catch unreachable;
}

fn writeSkillCurves(writer: *Io.Writer, data: SkillData) void {
    writer.print("pub const skill_shape = [_]SkillStep{{\n", .{}) catch unreachable;
    for (data.shape) |row| {
        writer.print(
            "    .{{ .required_advance = {d}, .gold = {d}, .costs = ",
            .{ row.required_advance, row.gold },
        ) catch unreachable;
        writeCosts(writer, row.costs);
        writer.writeAll(" },\n") catch unreachable;
    }
    writer.writeAll("};\n\npub const skill_materials = [_][" ++
        std.fmt.comptimePrint("{d}", .{skill_material_count}) ++
        "]u32{\n") catch unreachable;
    for (data.materials[0..data.material_set_count]) |material_set| {
        writer.writeAll("    .{ ") catch unreachable;
        for (material_set, 0..) |item_id, i| writer.print(
            "{d}{s} ",
            .{ item_id, if (i != skill_material_count - 1) "," else "" },
        ) catch unreachable;
        writer.writeAll("},\n") catch unreachable;
    }
    writer.writeAll("};\n\n") catch unreachable;
}

fn materialSet(groups: []const MaterialMapping, id: u32) u8 {
    for (groups) |group|
        if (group.group == id)
            return group.material_set;

    unreachable;
}

fn writeGrades(writer: *Io.Writer) void {
    writer.writeAll("pub const grades = [_]Grade{\n") catch unreachable;
    inline for (raw_grades) |raw| writer.print(
        "    .{{ .id = {d}, .fragments_per_node = {d} }},\n",
        .{ raw.value.grade, raw.value.fragments_qty },
    ) catch unreachable;
    writer.writeAll("};\n") catch unreachable;
}

fn writeCosts(writer: *Io.Writer, costs: Costs) void {
    writer.writeAll(".{ .entries = .{ ") catch unreachable;
    for (costs.entries) |cost| writer.print(
        ".{{ .material = {d}, .quantity = {d} }}, ",
        .{ cost.material, cost.quantity },
    ) catch unreachable;
    writer.print(" }}, .count = {d}, }},", .{costs.count}) catch unreachable;
}

fn buildLevelCosts() !LevelCostData {
    var curves: [raw_upgrade_count][level_cost_count]LevelCost = undefined;
    var curve_counts: [raw_upgrade_count]usize = @splat(0);
    var curve_keys: [raw_upgrade_count]u32 = undefined;
    var curve_count: usize = 0;

    inline for (raw_upgrades) |raw| {
        if (!@hasField(@TypeOf(raw), "exp"))
            continue;

        const key = levelCostGroup(raw);
        var curve_index: usize = 0;
        while (curve_index < curve_count and curve_keys[curve_index] != key) curve_index += 1;

        if (curve_index == curve_count) {
            curve_keys[curve_count] = key;
            curve_count += 1;
        }

        const row_index = curve_counts[curve_index];
        if (row_index >= level_cost_count or raw.level != row_index + 2)
            return error.InvalidLevelCostOrdering;

        curves[curve_index][row_index] = .{ .level = raw.level, .exp = raw.exp };
        curve_counts[curve_index] += 1;
    }

    if (curve_count == 0)
        return error.MissingLevelCosts;
    for (curve_counts[0..curve_count]) |count| if (count != level_cost_count)
        return error.InvalidLevelCostCount;
    for (curves[1..curve_count]) |curve|
        if (!std.meta.eql(
            curves[0],
            curve,
        ))
            return error.DuplicateLevelCostCurve;

    var max_exp: u32 = 0;
    for (curves[0]) |row| max_exp = @max(max_exp, row.exp);

    return .{ .rows = curves[0], .max_exp = max_exp };
}

fn buildLevelCaps() !LevelCapData {
    var curves: [raw_level_cap_count][level_cap_count]LevelCap = undefined;
    var curve_counts: [raw_level_cap_count]usize = @splat(0);
    var curve_keys: [raw_level_cap_count]u32 = undefined;
    var curve_count: usize = 0;

    inline for (raw_level_caps) |raw| {
        const key = raw.grade;
        var curve_index: usize = 0;
        while (curve_index < curve_count and curve_keys[curve_index] != key) curve_index += 1;
        if (curve_index == curve_count) {
            curve_keys[curve_count] = key;
            curve_count += 1;
        }
        const row_index = curve_counts[curve_index];
        if (row_index >= level_cap_count or fieldOrZero(raw, "advance_lvl") != row_index)
            return error.InvalidLevelCapOrdering;
        curves[curve_index][row_index] = .{
            .advance = @intCast(fieldOrZero(raw, "advance_lvl")),
            .level = @intCast(raw.lv_limit),
            .player_level = @intCast(raw.world_class_limit),
        };
        curve_counts[curve_index] += 1;
    }

    if (curve_count == 0)
        return error.MissingLevelCaps;
    for (curve_counts[0..curve_count]) |count|
        if (count != level_cap_count)
            return error.InvalidLevelCapCount;
    for (curves[1..curve_count]) |curve|
        if (!std.meta.eql(
            curves[0],
            curve,
        ))
            return error.DuplicateLevelCapCurve;

    return .{ .rows = curves[0] };
}

fn buildAdvances() !AdvanceData {
    var result: AdvanceData = undefined;
    result.material_set_count = 0;
    result.group_count = 0;
    var current: [advance_level_count]AdvanceEntry = undefined;
    var current_group: u32 = 0;
    var current_count: usize = 0;

    inline for (raw_advances) |raw| {
        if (current_count != 0 and raw.group != current_group) {
            try finishAdvance(&result, current_group, current, current_count);
            current_count = 0;
        }
        if (current_count == 0) current_group = raw.group;
        if (raw.advance_lvl != current_count + 1)
            return error.InvalidAdvanceOrdering;
        current[current_count] = .{
            .gold = @intCast(fieldOrZero(raw, "gold_qty")),
            .costs = costsFrom(raw),
        };
        current_count += 1;
    }

    if (current_count != 0)
        try finishAdvance(&result, current_group, current, current_count);

    return result;
}

fn finishAdvance(
    result: *AdvanceData,
    group: u32,
    curve: [advance_level_count]AdvanceEntry,
    count: usize,
) !void {
    if (count != advance_level_count)
        return error.InvalidAdvanceCount;
    const normalized = normalizeAdvance(curve);
    if (result.group_count == 0) {
        for (curve, normalized.costs, 0..) |row, costs, index| result.shape[index] = .{
            .gold = row.gold,
            .costs = costs,
        };
    } else {
        for (curve, normalized.costs, 0..) |row, costs, index|
            if (!std.meta.eql(
                result.shape[index],
                AdvanceStep{ .gold = row.gold, .costs = costs },
            ))
                return error.InconsistentAdvanceShape;
    }

    var material_set: usize = 0;
    while (material_set < result.material_set_count and
        !std.meta.eql(result.materials[material_set], normalized.materials)) material_set += 1;
    if (material_set == result.material_set_count) {
        result.materials[material_set] = normalized.materials;
        result.material_set_count += 1;
    }
    result.groups[result.group_count] = .{ .group = group, .material_set = @intCast(material_set) };
    result.group_count += 1;
}

fn buildSkills() !SkillData {
    var result: SkillData = undefined;
    result.material_set_count = 0;
    result.group_count = 0;
    result.max_required_advance = 0;
    var current: [skill_level_count]SkillEntry = undefined;
    var current_group: u32 = 0;
    var current_count: usize = 0;
    var previous_id: u32 = 0;

    inline for (raw_skill_upgrades) |raw| {
        if (current_count != 0 and raw.group != current_group) {
            try finishSkill(&result, current_group, current, current_count);
            current_count = 0;
        }
        if (current_count == 0) {
            current_group = raw.group;
            previous_id = raw.id - 1;
        }
        if (raw.id != previous_id + 1)
            return error.InvalidSkillUpgradeOrdering;
        const costs = costsFrom(raw);
        if (current_count == 0 and
            (fieldOrZero(raw, "advance_num") != 0 or
                fieldOrZero(raw, "gold_qty") != 0 or
                costs.count != 0))
            return error.InvalidInitialSkillUpgrade;
        const required_advance: u8 = @intCast(fieldOrZero(raw, "advance_num"));
        current[current_count] = .{
            .required_advance = required_advance,
            .gold = @intCast(fieldOrZero(raw, "gold_qty")),
            .costs = costs,
        };
        result.max_required_advance = @max(result.max_required_advance, required_advance);
        current_count += 1;
        previous_id = raw.id;
    }
    if (current_count != 0)
        try finishSkill(&result, current_group, current, current_count);

    return result;
}

fn finishSkill(
    result: *SkillData,
    group: u32,
    curve: [skill_level_count]SkillEntry,
    count: usize,
) !void {
    if (count != skill_level_count)
        return error.InvalidSkillUpgradeCount;
    const normalized = normalizeSkill(curve);
    if (result.group_count == 0) {
        for (curve, normalized.costs, 0..) |row, costs, index| result.shape[index] = .{
            .required_advance = row.required_advance,
            .gold = row.gold,
            .costs = costs,
        };
    } else {
        for (curve, normalized.costs, 0..) |row, costs, index|
            if (!std.meta.eql(
                result.shape[index],
                SkillStep{
                    .required_advance = row.required_advance,
                    .gold = row.gold,
                    .costs = costs,
                },
            ))
                return error.InconsistentSkillShape;
    }

    var material_set: usize = 0;
    while (material_set < result.material_set_count and
        !std.meta.eql(result.materials[material_set], normalized.materials)) material_set += 1;
    if (material_set == result.material_set_count) {
        result.materials[material_set] = normalized.materials;
        result.material_set_count += 1;
    }
    result.groups[result.group_count] = .{ .group = group, .material_set = @intCast(material_set) };
    result.group_count += 1;
}

fn normalizeAdvance(curve: [advance_level_count]AdvanceEntry) struct {
    costs: [advance_level_count]Costs,
    materials: [advance_material_count]u32,
} {
    var materials: [advance_material_count]u32 = undefined;
    var material_count: usize = 0;
    var costs: [advance_level_count]Costs = undefined;
    for (curve, 0..) |row, index|
        costs[index] = normalizeCosts(row.costs, &materials, &material_count);
    std.debug.assert(material_count == materials.len);

    return .{ .costs = costs, .materials = materials };
}

fn normalizeSkill(curve: [skill_level_count]SkillEntry) struct {
    costs: [skill_level_count]Costs,
    materials: [skill_material_count]u32,
} {
    var materials: [skill_material_count]u32 = undefined;
    var material_count: usize = 0;
    var costs: [skill_level_count]Costs = undefined;
    for (curve, 0..) |row, index|
        costs[index] = normalizeCosts(row.costs, &materials, &material_count);
    std.debug.assert(material_count == materials.len);

    return .{ .costs = costs, .materials = materials };
}

fn normalizeCosts(raw: RawCosts, materials: []u32, material_count: *usize) Costs {
    var result: Costs = .{};
    for (raw.entries[0..raw.count]) |cost| {
        var material: usize = 0;
        while (material < material_count.* and materials[material] != cost.item_id)
            material += 1;
        if (material == material_count.*) {
            std.debug.assert(material < materials.len);
            materials[material] = cost.item_id;
            material_count.* += 1;
        }
        result.entries[result.count] = .{
            .material = @intCast(material),
            .quantity = cost.quantity,
        };
        result.count += 1;
    }

    return result;
}

fn validateCharacters() !void {
    inline for (raw_characters) |raw| {
        const skill_group = raw.skills_upgrade_group[0];
        if (raw.skills_upgrade_group[1] != skill_group or
            raw.skills_upgrade_group[2] != skill_group or
            raw.skills_upgrade_group[3] != skill_group or
            raw.advance_group != raw.id or skill_group != raw.id or
            raw.fragments_id != raw.id * 10 or
            raw.default_skin_id != raw.id * 100 + 1 or
            raw.advance_skin_id != raw.id * 100 + 2 or
            raw.advance_skin_unlock_level != 3)
            return error.InvalidCharacterDerivation;
    }
}

fn validateTalentLayout() !TalentLayout {
    @setEvalBranchQuota(1_000_000);

    var groups_per_character: ?u8 = null;
    inline for (raw_characters) |character| {
        var count: u8 = 0;
        inline for (raw_talent_groups) |group| {
            if (group.char_id == character.id) count += 1;
        }
        if (groups_per_character) |expected| {
            if (count != expected)
                return error.InconsistentTalentGroupCount;
        } else groups_per_character = count;
    }

    const group_count = groups_per_character orelse
        return error.NoTalentGroups;
    if (group_count != 5)
        return error.InvalidTalentLayout;
    var max_index: u8 = 0;
    var max_entries: u8 = 0;
    inline for (raw_talent_groups) |group| {
        const group_number = group.id % 100;
        if (group.id / 100 != group.char_id or group_number == 0 or group_number > group_count or
            group.node_limit != 10 or group.background != group_number)
            return error.InvalidTalentGroup;
        var count: u8 = 0;
        var keys: u8 = 0;
        inline for (raw_talents) |talent| {
            if (talent.group_id != group.id)
                continue;
            count += 1;
            const base = (group_number - 1) * 16;
            const expected_index = if (talent.type == 1) base + 16 else base + talent.sort;
            if ((talent.type != 1 and talent.type != 2) or talent.index != expected_index or
                talent.id != group.id * 100 + talent.index)
                return error.InvalidTalentLayout;
            if (talent.type == 1) keys += 1;
            max_index = @max(max_index, talent.index);
        }
        if (count != group.node_limit + 1 or keys != 1)
            return error.InvalidTalentGroup;
        max_entries = @max(max_entries, count);
    }

    return .{
        .groups_per_character = group_count,
        .max_index = max_index,
        .max_entries_per_group = max_entries,
    };
}

fn maximumCostSlots(comptime rows: anytype) usize {
    @setEvalBranchQuota(1_000_000);

    var result: usize = 0;
    inline for (rows) |row| {
        inline for (@typeInfo(@TypeOf(row)).@"struct".fields) |field| {
            if (std.mem.startsWith(u8, field.name, "tid"))
                result = @max(result, std.fmt.parseInt(usize, field.name[3..], 10) catch unreachable);
        }
    }

    return result;
}

fn maximumMaterials(comptime rows: anytype) usize {
    @setEvalBranchQuota(1_000_000);

    var maximum: usize = 0;
    var current_group: u32 = 0;
    var materials: [rows.len]u32 = undefined;
    var count: usize = 0;

    inline for (rows) |row| {
        if (count != 0 and row.group != current_group) {
            maximum = @max(maximum, count);
            count = 0;
        }
        if (count == 0) current_group = row.group;
        const costs = costsFrom(row);
        for (costs.entries[0..costs.count]) |cost| {
            if (std.mem.indexOfScalar(u32, materials[0..count], cost.item_id) == null) {
                materials[count] = cost.item_id;
                count += 1;
            }
        }
    }

    return @max(maximum, count);
}

fn maximumRowsByField(comptime rows: anytype, comptime field: []const u8) usize {
    @setEvalBranchQuota(1_000_000);

    var result: usize = 0;

    inline for (rows) |row| {
        const value = @field(row, field);
        var count: usize = 0;
        inline for (rows) |candidate| {
            if (@field(candidate, field) == value) count += 1;
        }
        result = @max(result, count);
    }

    return result;
}

fn countGroups(comptime rows: anytype, comptime field: []const u8) usize {
    var result: usize = 0;
    var previous: u32 = 0;

    inline for (rows) |row| {
        const value: u32 = @intCast(@field(row, field));
        if (result == 0 or value != previous) {
            result += 1;
            previous = value;
        }
    }

    return result;
}

fn maximumRowsByKey(comptime rows: anytype, comptime key_fn: anytype) usize {
    @setEvalBranchQuota(1_000_000);

    var result: usize = 0;

    inline for (rows) |row| {
        if (!@hasField(@TypeOf(row), "exp")) continue;
        const value = key_fn(row);
        var count: usize = 0;
        inline for (rows) |candidate| {
            if (@hasField(@TypeOf(candidate), "exp") and key_fn(candidate) == value) count += 1;
        }
        result = @max(result, count);
    }

    return result;
}

fn levelCostGroup(row: anytype) u32 {
    return (row.id - 10_000) / 1_000;
}

fn costsFrom(raw: anytype) RawCosts {
    var result: RawCosts = .{};
    inline for (1..max_costs + 1) |index| {
        const suffix = std.fmt.comptimePrint("{d}", .{index});
        const tid_name = "tid" ++ suffix;
        const qty_name = "qty" ++ suffix;
        if (@hasField(@TypeOf(raw), tid_name) and @field(raw, tid_name) != 0) {
            result.entries[result.count] = .{
                .item_id = @field(raw, tid_name),
                .quantity = @field(raw, qty_name),
            };
            result.count += 1;
        }
    }

    return result;
}

fn fieldOrZero(value: anytype, comptime name: []const u8) u32 {
    if (@hasField(@TypeOf(value), name))
        return @intCast(@field(value, name));

    return 0;
}
