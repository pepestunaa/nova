const std = @import("std");
const Io = std.Io;

const handbook = @import("tables/Handbook");
const item = @import("tables/Item");
const mall_gem = @import("tables/MallGem");
const mall_monthly_card = @import("tables/MallMonthlyCard");
const mall_package = @import("tables/MallPackage");
const mall_shop = @import("tables/MallShop");
const monthly_card = @import("tables/MonthlyCard");
const time = @import("table_time");

const Reward = struct { id: u32, quantity: i32 };

pub fn generate(_: std.process.Init, writer: *Io.Writer) !void {
    const max_package_rewards = comptime maxPackageRewards();
    try writer.writeAll(
        "//! Generated by `zig build generate-assets -- shop`.\n" ++
            "//! Do not edit manually.\n\n" ++
            "pub const Reward = struct { id: u32, quantity: i32 };\n" ++
            "pub const RefreshType = enum(u8) { none = 0, day = 1, week = 2, month = 3 };\n" ++
            "pub fn productKey(id: []const u8) u64 {\n" ++
            "    var hash: u64 = 14_695_981_039_346_656_037;\n" ++
            "    for (id) |byte| hash = (hash ^ byte) *% 1_099_511_628_211;\n" ++
            "    return hash;\n" ++
            "}\n\n" ++
            "pub const MallMonthlyCard = struct { id: []const u8, key: u64, monthly_card_id: u32, base_resource_id: u32, base_quantity: i32, duration_days: u32, max_days: u32, daily_rewards: [2]Reward };\n" ++
            "pub const MallGem = struct { id: []const u8, key: u64, base_quantity: i32, experienced_bonus_quantity: i32, maiden_bonus_quantity: i32, base_item_id: u32, experienced_bonus_item_id: u32, maiden_bonus_item_id: u32 };\n" ++
            "pub const MallShop = struct { id: u32, key: u64, stock: i32, currency_id: u32, price: i32, item_id: u32, item_quantity: i32, starts_at: i64, ends_at: i64, refresh_type: RefreshType };\n" ++
            "\n",
    );
    try writer.print("pub const max_package_rewards = {d};\npub const MallPackage = struct {{ id: []const u8, key: u64, stock: u32, starts_at: i64, ends_at: i64, refresh_type: RefreshType, rewards: [max_package_rewards]Reward, reward_count: usize }};\n\n", .{max_package_rewards});
    try writeMallPackages(writer, max_package_rewards);
    try writeMonthlyCards(writer);
    try writeMallGems(writer);
    try writeMallShop(writer);
}

fn maxPackageRewards() usize {
    @setEvalBranchQuota(1_000_000);
    var result: usize = 1;
    inline for (mall_package) |entry|
        result = @max(result, rewardCount(entry.items));
    return result;
}

fn writeMallPackages(writer: *Io.Writer, comptime capacity: usize) !void {
    try writer.writeAll("pub const mall_packages = [_]MallPackage{\n");
    inline for (mall_package, 0..) |entry, index| {
        validateProductId(entry.id, "MallPackage");
        ensureUniqueKey(mall_package, index, entry.id, "MallPackage");
        const rewards = rewardsFromJson(entry.items, capacity);
        validateWindow(timeField(entry, "list_time"), timeField(entry, "de_list_time"), "MallPackage");
        try writer.print("    .{{ .id = \"{s}\", .key = {d}, .stock = {d}, .starts_at = {d}, .ends_at = {d}, .refresh_type = .{s}, .rewards = .{{", .{
            entry.id,                         productKey(entry.id),                           entry.stock, timeField(entry, "list_time"),
            timeField(entry, "de_list_time"), refreshName(fieldOr(entry, "refresh_type", 0)),
        });
        for (rewards.values[0..rewards.len]) |reward|
            try writer.print(" .{{ .id = {d}, .quantity = {d} }},", .{ reward.id, reward.quantity });
        for (rewards.len..capacity) |_|
            try writer.writeAll(" .{ .id = 0, .quantity = 0 },");
        try writer.print(" }}, .reward_count = {d} }},\n", .{rewards.len});
    }
    try writer.writeAll("};\n\n");
}

fn writeMonthlyCards(writer: *Io.Writer) !void {
    try writer.writeAll("pub const mall_monthly_cards = [_]MallMonthlyCard{\n");
    inline for (mall_monthly_card, 0..) |entry, index| {
        validateProductId(entry.id, "MallMonthlyCard");
        ensureUniqueKey(mall_monthly_card, index, entry.id, "MallMonthlyCard");
        const daily = dailyCard(entry.monthly_card_id);
        if (entry.max_days == 0 or daily.duration > entry.max_days)
            @panic("invalid MallMonthlyCard duration");
        validateResource(entry.base_item_id, entry.base_item_qty, "MallMonthlyCard base reward");
        inline for (daily.rewards) |reward|
            validateReward(reward.id, reward.quantity, "MonthlyCard daily reward");
        try writer.print("    .{{ .id = \"{s}\", .key = {d}, .monthly_card_id = {d}, .base_resource_id = {d}, .base_quantity = {d}, .duration_days = {d}, .max_days = {d}, .daily_rewards = .{{ .{{ .id = {d}, .quantity = {d} }}, .{{ .id = {d}, .quantity = {d} }} }} }},\n", .{
            entry.id,                  productKey(entry.id), entry.monthly_card_id, entry.base_item_id,        entry.base_item_qty,
            daily.duration,            entry.max_days,       daily.rewards[0].id,   daily.rewards[0].quantity, daily.rewards[1].id,
            daily.rewards[1].quantity,
        });
    }
    try writer.writeAll("};\n\n");
}

fn writeMallGems(writer: *Io.Writer) !void {
    try writer.writeAll("pub const mall_gems = [_]MallGem{\n");
    inline for (mall_gem, 0..) |entry, index| {
        validateProductId(entry.id, "MallGem");
        ensureUniqueKey(mall_gem, index, entry.id, "MallGem");
        validateResource(entry.base_item_id, entry.base_item_qty, "MallGem base reward");
        validateResource(entry.experienced_bonus_item_id, entry.experienced_bonus_item_qty, "MallGem experienced bonus");
        validateResource(entry.maiden_bonus_item_id, entry.maiden_bonus_item_qty, "MallGem maiden bonus");
        try writer.print("    .{{ .id = \"{s}\", .key = {d}, .base_quantity = {d}, .experienced_bonus_quantity = {d}, .maiden_bonus_quantity = {d}, .base_item_id = {d}, .experienced_bonus_item_id = {d}, .maiden_bonus_item_id = {d} }},\n", .{
            entry.id,                    productKey(entry.id), entry.base_item_qty,             entry.experienced_bonus_item_qty,
            entry.maiden_bonus_item_qty, entry.base_item_id,   entry.experienced_bonus_item_id, entry.maiden_bonus_item_id,
        });
    }
    try writer.writeAll("};\n\n");
}

fn writeMallShop(writer: *Io.Writer) !void {
    try writer.writeAll("pub const mall_shop = [_]MallShop{\n");
    inline for (mall_shop, 0..) |entry, index| {
        validateProductId(entry.id, "MallShop");
        ensureUniqueKey(mall_shop, index, entry.id, "MallShop");
        validateWindow(timeField(entry, "list_time"), timeField(entry, "de_list_time"), "MallShop");
        validateResource(entry.exchange_item_id, entry.exchange_item_qty, "MallShop price");
        validateReward(entry.item_id, entry.item_qty, "MallShop reward");
        try writer.print("    .{{ .id = {d}, .key = {d}, .stock = {d}, .currency_id = {d}, .price = {d}, .item_id = {d}, .item_quantity = {d}, .starts_at = {d}, .ends_at = {d}, .refresh_type = .{s} }},\n", .{
            parseU32(entry.id),               productKey(entry.id),                           fieldOr(entry, "stock", 0), entry.exchange_item_id,
            entry.exchange_item_qty,          entry.item_id,                                  entry.item_qty,             timeField(entry, "list_time"),
            timeField(entry, "de_list_time"), refreshName(fieldOr(entry, "refresh_type", 0)),
        });
    }
    try writer.writeAll("};\n\n");
}

fn validateProductId(id: []const u8, comptime table: []const u8) void {
    if (id.len == 0)
        std.debug.panic("{s} id is malformed", .{table});
    for (id) |byte| switch (byte) {
        'A'...'Z', 'a'...'z', '0'...'9', '_', '-', '.' => {},
        else => std.debug.panic("{s} id contains an unsafe character", .{table}),
    };
}

fn validateWindow(starts_at: i64, ends_at: i64, comptime table: []const u8) void {
    if (starts_at != 0 and ends_at != 0 and starts_at >= ends_at)
        std.debug.panic("{s} has an invalid availability window", .{table});
}

fn validateResource(id: u32, quantity: i32, comptime context: []const u8) void {
    if (quantity <= 0 or !isResource(id))
        std.debug.panic("{s} is not a positive resource reward", .{context});
}

fn validateReward(id: u32, quantity: i32, comptime context: []const u8) void {
    if (quantity <= 0 or !isReward(id))
        std.debug.panic("{s} is not a positive item, resource, or skin reward", .{context});
}

fn isResource(id: u32) bool {
    @setEvalBranchQuota(1_000_000);
    inline for (item) |entry|
        if (entry.id == id)
            return entry.type == 1;
    return false;
}

fn isReward(id: u32) bool {
    @setEvalBranchQuota(1_000_000);
    inline for (item) |entry|
        if (entry.id == id)
            return true;
    inline for (handbook) |entry| {
        if (@hasField(@TypeOf(entry), "skin_id") and entry.skin_id == id)
            return true;
    }
    return false;
}

fn ensureUniqueKey(comptime source: anytype, comptime index: usize, comptime id: []const u8, comptime table: []const u8) void {
    inline for (source, 0..) |other, other_index| {
        if (comptime other_index >= index)
            continue;
        if (comptime productKey(other.id) == productKey(id))
            @compileError(table ++ " product key collision");
    }
}

fn productKey(comptime id: []const u8) u64 {
    var hash: u64 = 14_695_981_039_346_656_037;
    inline for (id) |byte| hash = (hash ^ byte) *% 1_099_511_628_211;
    return hash;
}

fn fieldOr(comptime entry: anytype, comptime name: []const u8, comptime fallback: anytype) @TypeOf(fallback) {
    return if (@hasField(@TypeOf(entry), name)) @field(entry, name) else fallback;
}

fn timeField(comptime entry: anytype, comptime name: []const u8) i64 {
    return if (@hasField(@TypeOf(entry), name)) time.parseTime(@field(entry, name)) else 0;
}

fn refreshName(comptime value: u8) []const u8 {
    return switch (value) {
        0 => "none",
        1 => "day",
        2 => "week",
        3 => "month",
        else => @compileError("unsupported Shop refresh type"),
    };
}

fn rewardCount(comptime text: []const u8) usize {
    var index: usize = 0;
    var count: usize = 0;
    expectByte(text, &index, '{');
    if (peekByte(text, &index) == '}') {
        index += 1;
        return 0;
    }
    while (true) {
        _ = parseQuotedU32(text, &index);
        expectByte(text, &index, ':');
        _ = parseI32(text, &index);
        count += 1;
        switch (nextByte(text, &index)) {
            ',' => continue,
            '}' => break,
            else => @panic("malformed MallPackage items"),
        }
    }
    if (index != text.len) @panic("malformed MallPackage items");
    return count;
}

fn rewardsFromJson(comptime text: []const u8, comptime capacity: usize) struct { values: [capacity]Reward, len: usize } {
    var values: [capacity]Reward = @splat(.{ .id = 0, .quantity = 0 });
    var index: usize = 0;
    var len: usize = 0;
    expectByte(text, &index, '{');
    if (peekByte(text, &index) == '}') {
        index += 1;
        return .{ .values = values, .len = 0 };
    }
    while (true) {
        const id = parseQuotedU32(text, &index);
        var duplicate = false;
        for (values[0..len]) |existing| {
            if (existing.id == id)
                duplicate = true;
        }
        if (duplicate)
            @panic("duplicate MallPackage reward id");
        expectByte(text, &index, ':');
        const quantity = parseI32(text, &index);
        validateReward(id, quantity, "MallPackage reward");
        values[len] = .{ .id = id, .quantity = quantity };
        len += 1;
        switch (nextByte(text, &index)) {
            ',' => continue,
            '}' => break,
            else => @panic("malformed MallPackage items"),
        }
    }
    if (index != text.len) @panic("malformed MallPackage items");
    return .{ .values = values, .len = len };
}

fn nextByte(comptime text: []const u8, index: *usize) u8 {
    const result = peekByte(text, index);
    index.* += 1;
    return result;
}

fn peekByte(comptime text: []const u8, index: *usize) u8 {
    while (index.* < text.len and switch (text[index.*]) {
        ' ', '\t', '\n', '\r' => true,
        else => false,
    }) index.* += 1;
    if (index.* == text.len) @panic("unexpected end of Shop JSON");
    return text[index.*];
}

fn expectByte(comptime text: []const u8, index: *usize, expected: u8) void {
    if (nextByte(text, index) != expected) @panic("malformed MallPackage items");
}

fn parseQuotedU32(comptime text: []const u8, index: *usize) u32 {
    expectByte(text, index, '"');
    const start = index.*;
    while (index.* < text.len and text[index.*] >= '0' and text[index.*] <= '9') index.* += 1;
    if (start == index.* or index.* == text.len or text[index.*] != '"') @panic("MallPackage reward id must be a quoted u32");
    const value = parseU32(text[start..index.*]);
    index.* += 1;
    return value;
}

fn parseU32(text: []const u8) u32 {
    return std.fmt.parseInt(u32, text, 10) catch @panic("invalid Shop u32 value");
}

fn parseI32(comptime text: []const u8, index: *usize) i32 {
    const start = index.*;
    if (index.* < text.len and text[index.*] == '-') index.* += 1;
    const digits = index.*;
    while (index.* < text.len and text[index.*] >= '0' and text[index.*] <= '9') index.* += 1;
    if (digits == index.*) @panic("MallPackage reward quantity must be an i32");
    return std.fmt.parseInt(i32, text[start..index.*], 10) catch @panic("invalid MallPackage reward quantity");
}

fn dailyCard(comptime card_id: u32) struct { duration: u32, rewards: [2]Reward } {
    var count: u32 = 0;
    var rewards: ?[2]Reward = null;
    inline for (monthly_card) |entry| if (entry.card_id == card_id) {
        const current = [_]Reward{ .{ .id = entry.reward_id1, .quantity = entry.reward_num1 }, .{ .id = entry.reward_id2, .quantity = entry.reward_num2 } };
        if (rewards) |expected| {
            if (!std.meta.eql(expected, current)) @panic("inconsistent MonthlyCard daily rewards");
        } else rewards = current;
        count = std.math.add(u32, count, 1) catch @panic("MonthlyCard duration overflow");
    };
    if (count == 0) @panic("MallMonthlyCard is missing MonthlyCard rewards");
    return .{ .duration = count, .rewards = rewards.? };
}
