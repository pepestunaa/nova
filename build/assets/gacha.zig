const std = @import("std");
const Io = std.Io;

const raw_a_type_probabilities = @import("tables/GachaATypeProb");
const raw_acquire_rewards = @import("tables/AcquireReward");
const raw_banners = @import("tables/Gacha");
const raw_packages = @import("tables/GachaPkg");
const raw_storages = @import("tables/GachaStorage");

//

const ItemReward = struct {
    id: u32,
    quantity: i32,
};

const Storage = struct {
    id: u32,
    ticket_id: u32,
    tickets_per_pull: u32,
    currency_id: u32,
    currency_per_ticket: u32,
    a_type_group: u32,
    a_up_probability: u32,
    a_up_guarantee_pulls: u32,
    b_probability: u32,
    b_up_probability: u32,
    b_guarantee_probability: u32,
    give_item: ?ItemReward,
};

pub fn generate(_: std.process.Init, writer: *Io.Writer) anyerror!void {
    @setEvalBranchQuota(10_000_000);

    try writer.writeAll(
        \\//! Generated by `zig build generate-assets -- gacha`.
        \\//! Do not edit manually.
        \\
        \\pub const PackageEntry = struct {
        \\    goods_id: u32,
        \\    weight: u32,
        \\};
        \\
        \\pub const ItemReward = struct {
        \\    id: u32,
        \\    quantity: i32,
        \\};
        \\
        \\pub const Storage = struct {
        \\    id: u32,
        \\    ticket_id: u32,
        \\    tickets_per_pull: u32,
        \\    currency_id: u32,
        \\    currency_per_ticket: u32,
        \\    a_type_group: u32,
        \\    a_up_probability: u32,
        \\    a_up_guarantee_pulls: u32,
        \\    b_probability: u32,
        \\    b_up_probability: u32,
        \\    b_guarantee_probability: u32,
        \\    give_item: ?ItemReward,
        \\};
        \\
        \\pub const Reward = struct {
        \\    resource_id: u32,
        \\    quantity: i32,
        \\};
        \\
        \\pub const Banner = struct {
        \\    id: u32,
        \\    gacha_type: u32,
        \\    storage_id: u32,
        \\    storage: Storage,
        \\    a_type_guarantee_pulls: u32,
        \\    a_pool: []const PackageEntry,
        \\    a_up_pool: []const PackageEntry,
        \\    b_pool: []const PackageEntry,
        \\    b_up_pool: []const PackageEntry,
        \\    b_guarantee_pool: []const PackageEntry,
        \\    c_pool: []const PackageEntry,
        \\    claim_reward_pulls: u32,
        \\    claim_reward: ?Reward,
        \\    first_ten_reward_multiplier: u32,
        \\};
        \\
        \\pub const AcquireRewardDefinition = struct {
        \\    item_stype: u8,
        \\    item_rarity: u8,
        \\    acquire_times: u32,
        \\    reward: ?Reward,
        \\};
        \\
    );

    try writePackages(writer);
    try writeAcquireRewards(writer);
    try writeBanners(writer);
    try writeATypeProbabilities(writer);
}

fn writePackages(writer: *Io.Writer) !void {
    @setEvalBranchQuota(10_000_000);

    var current_id: ?u32 = null;
    var seen: [raw_packages.len]u32 = undefined;
    var seen_count: usize = 0;

    inline for (raw_packages) |raw| {
        const entry = raw.value;
        if (current_id == null or current_id.? != entry.pkg_id) {
            if (current_id != null)
                try writer.writeAll("};\n\n");
            for (seen[0..seen_count]) |id|
                if (id == entry.pkg_id)
                    return error.NonContiguousPackage;
            seen[seen_count] = entry.pkg_id;
            seen_count += 1;
            current_id = entry.pkg_id;
            try writer.print(
                "const package_{d} = [_]PackageEntry{{\n",
                .{entry.pkg_id},
            );
        }
        try writer.print(
            "    .{{ .goods_id = {d}, .weight = {d} }},\n",
            .{ entry.goods_id, entry.weight },
        );
    }
    if (current_id != null)
        try writer.writeAll("};\n\n");
}

fn writeAcquireRewards(writer: *Io.Writer) !void {
    try writer.writeAll("pub const acquire_rewards = [_]AcquireRewardDefinition{\n");
    inline for (raw_acquire_rewards) |entry| {
        const quantity = fieldOrZero(entry, "item_num");
        try writer.print(
            "    .{{ .item_stype = {d}, .item_rarity = {d}, .acquire_times = {d}, .reward = ",
            .{ entry.item_stype, entry.item_rarity, entry.acquire_times },
        );
        if (quantity == 0) {
            try writer.writeAll("null");
        } else {
            try writer.print(
                ".{{ .resource_id = {d}, .quantity = {d} }}",
                .{ entry.item_id, quantity },
            );
        }
        try writer.writeAll(" },\n");
    }
    try writer.writeAll("};\n\n");
}

fn writeBanners(writer: *Io.Writer) !void {
    try writer.writeAll("pub const banners = [_]Banner{\n");
    inline for (raw_banners) |entry| {
        const storage = storageFor(entry.storage_id);
        const guarantee = if (@hasField(@TypeOf(entry), "a_type_guarantee_times"))
            entry.a_type_guarantee_times
        else
            storage.a_up_guarantee_pulls;
        try writer.print(
            \\    .{{
            \\        .id = {d},
            \\        .gacha_type = {d},
            \\        .storage_id = {d},
            \\        .storage = .{{
            \\            .id = {d},
            \\            .ticket_id = {d},
            \\            .tickets_per_pull = {d},
            \\            .currency_id = {d},
            \\            .currency_per_ticket = {d},
            \\            .a_type_group = {d},
            \\            .a_up_probability = {d},
            \\            .a_up_guarantee_pulls = {d},
            \\            .b_probability = {d},
            \\            .b_up_probability = {d},
            \\            .b_guarantee_probability = {d},
            \\            .give_item =
        , .{
            entry.id,
            entry.gacha_type,
            entry.storage_id,
            storage.id,
            storage.ticket_id,
            storage.tickets_per_pull,
            storage.currency_id,
            storage.currency_per_ticket,
            storage.a_type_group,
            storage.a_up_probability,
            storage.a_up_guarantee_pulls,
            storage.b_probability,
            storage.b_up_probability,
            storage.b_guarantee_probability,
        });
        if (storage.give_item) |item|
            try writer.print(
                ".{{ .id = {d}, .quantity = {d} }}",
                .{ item.id, item.quantity },
            )
        else
            try writer.writeAll("null");
        try writer.writeAll(",\n        },\n");
        try writer.print("        .a_type_guarantee_pulls = {d},\n", .{guarantee});
        try writePool(writer, "a_pool", fieldOrZero(entry, "a_type_pkg"));
        try writePool(writer, "a_up_pool", fieldOrZero(entry, "a_type_up_pkg"));
        try writePool(writer, "b_pool", fieldOrZero(entry, "b_type_pkg"));
        try writePool(writer, "b_up_pool", fieldOrZero(entry, "b_type_up_pkg"));
        try writePool(writer, "b_guarantee_pool", fieldOrZero(entry, "b_guarantee_pkg"));
        try writePool(writer, "c_pool", fieldOrZero(entry, "c_type_pkg"));
        try writer.print(
            "        .claim_reward_pulls = {d},\n        .claim_reward = ",
            .{fieldOrZero(entry, "guarantee_times")},
        );
        const reward_id = fieldOrZero(entry, "guarantee_tid");
        const reward_quantity = fieldOrZero(entry, "guarantee_qty");
        if (reward_id == 0 or reward_quantity == 0)
            try writer.writeAll("null")
        else
            try writer.print(
                ".{{ .resource_id = {d}, .quantity = {d} }}",
                .{ reward_id, reward_quantity },
            );
        try writer.print(
            ",\n        .first_ten_reward_multiplier = {d},\n    }},\n",
            .{if (@hasField(@TypeOf(entry), "first_ten_show")) entry.first_ten_show else 1},
        );
    }
    try writer.writeAll("};\n\npub const banner_ids = [_]u32{\n");
    inline for (raw_banners) |entry|
        try writer.print("    {d},\n", .{entry.id});
    try writer.writeAll("};\n\n");
}

fn writePool(writer: *Io.Writer, name: []const u8, package_id: u32) !void {
    if (package_id == 0)
        try writer.print("        .{s} = &.{{}},\n", .{name})
    else
        try writer.print("        .{s} = &package_{d},\n", .{ name, package_id });
}

fn writeATypeProbabilities(writer: *Io.Writer) !void {
    try writer.writeAll("pub const a_type_probability_keys = [_]u64{\n");
    inline for (raw_a_type_probabilities) |entry| {
        const value = entry.value;
        const times = fieldOrZero(value, "times");
        try writer.print("    {d},\n", .{(@as(u64, value.group) << 32) | times});
    }
    try writer.writeAll("};\n\npub const a_type_probabilities = [_]u32{\n");
    inline for (raw_a_type_probabilities) |entry|
        try writer.print("    {d},\n", .{entry.value.prob});
    try writer.writeAll("};\n");
}

fn storageFor(comptime id: u32) Storage {
    inline for (raw_storages) |entry|
        if (entry.id == id)
            return .{
                .id = entry.id,
                .ticket_id = entry.default_id,
                .tickets_per_pull = entry.default_qty,
                .currency_id = fieldOrZero(entry, "cost_id"),
                .currency_per_ticket = fieldOrZero(entry, "cost_qty"),
                .a_type_group = entry.a_type_group,
                .a_up_probability = fieldOrZero(entry, "a_type_up_prob"),
                .a_up_guarantee_pulls = fieldOrZero(entry, "a_up_guarantee_times"),
                .b_probability = entry.b_type_prob,
                .b_up_probability = fieldOrZero(entry, "b_type_up_prob"),
                .b_guarantee_probability = fieldOrZero(entry, "b_type_guarantee_prob"),
                .give_item = if (@hasField(@TypeOf(entry), "give_items"))
                    parseGiveItem(entry.give_items)
                else
                    null,
            };

    @compileError("Gacha refers to a missing GachaStorage entry");
}

fn fieldOrZero(value: anytype, comptime name: []const u8) u32 {
    if (@hasField(@TypeOf(value), name))
        return @intCast(@field(value, name));
    return 0;
}

fn parseGiveItem(encoded: []const u8) ItemReward {
    const first_quote = std.mem.indexOfScalar(u8, encoded, '"') orelse unreachable;
    const after_first_quote = encoded[first_quote + 1 ..];
    const second_quote = std.mem.indexOfScalar(u8, after_first_quote, '"') orelse unreachable;
    const id = std.fmt.parseInt(u32, after_first_quote[0..second_quote], 10) catch unreachable;
    const after_id = after_first_quote[second_quote + 1 ..];
    const colon = std.mem.indexOfScalar(u8, after_id, ':') orelse unreachable;
    const quantity_text = std.mem.trim(u8, after_id[colon + 1 .. after_id.len - 1], " \t\r\n}");
    const quantity = std.fmt.parseInt(i32, quantity_text, 10) catch unreachable;

    return .{ .id = id, .quantity = quantity };
}
