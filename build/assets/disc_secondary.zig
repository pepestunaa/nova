const std = @import("std");
const Io = std.Io;

const raw_discs = @import("tables/Disc");
const raw_skills = @import("tables/SecondarySkill");
const raw_support_note_groups = @import("tables/SubNoteSkillPromoteGroup");

//

const max_requirements = 3;

const Requirement = struct {
    note_id: u32 = 0,
    quantity: u32 = 0,
};

const Requirements = struct {
    entries: [max_requirements]Requirement = @splat(.{}),
    count: u8 = 0,
};

pub fn generate(_: std.process.Init, writer: *Io.Writer) anyerror!void {
    @setEvalBranchQuota(10_000_000);

    try writer.writeAll(
        \\//! Generated by `zig build generate-assets -- disc_secondary`.
        \\//! Do not edit manually.
        \\
    ++ std.fmt.comptimePrint("\npub const max_requirements = {d};\n", .{max_requirements}) ++
        \\
        \\pub const Requirement = struct {
        \\    note_id: u32,
        \\    quantity: u32,
        \\};
        \\
        \\pub const Disc = struct {
        \\    id: u32,
        \\    groups: [2]u32,
        \\    support_note_group_id: u32,
        \\};
        \\
        \\pub const Skill = struct {
        \\    id: u32,
        \\    group_id: u32,
        \\    level: u8,
        \\    score: u32,
        \\    requirements: [max_requirements]Requirement,
        \\    requirement_count: u8,
        \\};
        \\
        \\pub const SupportNoteDefinition = struct {
        \\    group_id: u32,
        \\    phase: u32,
        \\    requirements: [max_requirements]Requirement,
        \\    requirement_count: u8,
        \\};
        \\
    );

    try writer.writeAll("pub const discs = [_]Disc{\n");
    inline for (raw_discs) |raw| try writer.print(
        "    .{{ .id = {d}, .groups = .{{ {d}, {d} }}, .support_note_group_id = {d} }},\n",
        .{
            raw.id,
            fieldOrZero(raw, "secondary_skill_group_id1"),
            fieldOrZero(raw, "secondary_skill_group_id2"),
            fieldOrZero(raw, "sub_note_skill_group_id"),
        },
    );
    try writer.writeAll("};\n\npub const support_note_definitions = [_]SupportNoteDefinition{\n");
    inline for (raw_support_note_groups) |raw| {
        const parsed = parseRequirements(raw.sub_note_skills);
        try writer.print(
            "    .{{ .group_id = {d}, .phase = {d}, .requirements = ",
            .{ raw.group_id, fieldOrZero(raw, "phase") },
        );
        try writeRequirements(writer, parsed);
        try writer.print(", .requirement_count = {d},}},\n", .{parsed.count});
    }
    try writer.writeAll("};\n\npub const skills = [_]Skill{\n");
    inline for (raw_skills) |raw| {
        const parsed = parseRequirements(raw.need_sub_note_skills);
        try writer.print(
            "    .{{ .id = {d}, .group_id = {d}, .level = {d}, .score = {d}, .requirements = ",
            .{ raw.id, fieldOrZero(raw, "group_id"), fieldOrZero(raw, "level"), raw.score },
        );
        try writeRequirements(writer, parsed);
        try writer.print(", .requirement_count = {d}, }},\n", .{parsed.count});
    }
    try writer.writeAll("};\n");
}

fn writeRequirements(writer: *Io.Writer, requirements: Requirements) !void {
    try writer.writeAll(".{\n");
    for (requirements.entries) |entry|
        try writer.print(
            "        .{{ .note_id = {d}, .quantity = {d} }},\n",
            .{ entry.note_id, entry.quantity },
        );
    try writer.writeAll("    }");
}

fn fieldOrZero(value: anytype, comptime name: []const u8) u32 {
    if (@hasField(@TypeOf(value), name))
        return @intCast(@field(value, name));
    return 0;
}

fn parseRequirements(text: []const u8) Requirements {
    var result: Requirements = .{};
    var cursor: usize = 0;
    while (cursor < text.len) {
        while (cursor < text.len and text[cursor] != '"') cursor += 1;
        if (cursor == text.len) break;
        cursor += 1;
        const note_id = parseDecimal(text, &cursor);
        while (cursor < text.len and text[cursor] != ':') cursor += 1;
        if (cursor == text.len) unreachable;
        cursor += 1;
        const quantity = parseDecimal(text, &cursor);
        if (result.count == result.entries.len) unreachable;
        result.entries[result.count] = .{ .note_id = note_id, .quantity = quantity };
        result.count += 1;
    }

    return result;
}

fn parseDecimal(text: []const u8, cursor: *usize) u32 {
    var value: u32 = 0;
    var found_digit = false;
    while (cursor.* < text.len and std.ascii.isDigit(text[cursor.*])) : (cursor.* += 1) {
        found_digit = true;
        value = value * 10 + text[cursor.*] - '0';
    }
    if (!found_digit) unreachable;

    return value;
}
